const langListeners = new Set<() => void>();

function emitLobbyLang(): void {
  for (const listener of langListeners) listener();
}

export function loadLobbyLang(): LobbyLang {
  if (typeof window === "undefined") return "zh-CN";
  const raw = window.localStorage.getItem(LOBBY_LANG_STORAGE);
  if (isLobbyLang(raw)) return raw;
  return "zh-CN";
}

export function saveLobbyLang(lang: LobbyLang): void {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LOBBY_LANG_STORAGE, lang);
  writeLangCookie(lang);
  emitLobbyLang();
}

/** SSR-safe subscribe for lobby language (avoids hydration setState-in-effect). */
export function subscribeLobbyLang(onStoreChange: () => void): () => void {
  langListeners.add(onStoreChange);
  const onStorage = (e: StorageEvent) => {
    if (e.key === LOBBY_LANG_STORAGE || e.key === null) onStoreChange();
  };
  if (typeof window !== "undefined") {
    window.addEventListener("storage", onStorage);
  }
  return () => {
    langListeners.delete(onStoreChange);
    if (typeof window !== "undefined") {
      window.removeEventListener("storage", onStorage);
    }
  };
}

